// Vite plugin: emits a precaching service worker (M9.1 offline play).
//
// Every built JS/CSS chunk and every file in the public dir (assets/) is
// listed in the worker together with a content hash. The hash is part of
// the cache name, so a new deploy → new sw.js bytes → the browser installs
// the new worker, which precaches the new files and deletes old caches.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';
import { SW_CACHE_PREFIX, SW_FILENAME, SW_PRECACHE_EXCLUDE } from '../../src/config/offline';

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

const excluded = (file: string): boolean => SW_PRECACHE_EXCLUDE.some((re) => re.test(file));

export function serviceWorkerPlugin(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'pf-service-worker',
    apply: 'build',
    configResolved(c) {
      config = c;
    },
    generateBundle(_opts, bundle) {
      const hash = createHash('sha256');
      const files: string[] = [];
      for (const [fileName, item] of Object.entries(bundle)) {
        if (excluded(fileName)) continue;
        files.push(fileName);
        hash.update(fileName);
        hash.update(item.type === 'chunk' ? item.code : item.source);
      }
      if (config.publicDir) {
        for (const full of walk(config.publicDir)) {
          const rel = relative(config.publicDir, full).split(sep).join('/');
          if (excluded(rel)) continue;
          files.push(rel);
          hash.update(rel);
          hash.update(readFileSync(full));
        }
      }
      files.sort();
      // The worker's own code is part of the version too.
      hash.update(workerSource('', files));
      const version = hash.digest('hex').slice(0, 12);
      this.emitFile({
        type: 'asset',
        fileName: SW_FILENAME,
        source: workerSource(SW_CACHE_PREFIX + version, ['./', ...files]),
      });
    },
  };
}

function workerSource(cacheName: string, files: string[]): string {
  return `// Generated by tools/build/serviceWorkerPlugin.ts — do not edit.
const CACHE = ${JSON.stringify(cacheName)};
const PREFIX = ${JSON.stringify(SW_CACHE_PREFIX)};
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(FILES.map((f) => new Request(f, { cache: 'reload' }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // Page navigations: network first so a new deploy is picked up on the
  // next launch; fall back to the cached shell when offline.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./', { cacheName: CACHE, ignoreVary: true })),
    );
    return;
  }
  // Everything else is content-addressed or versioned with the cache:
  // cache first, network as a fallback (and remember the answer).
  event.respondWith(
    caches.match(req, { cacheName: CACHE, ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy));
      }
      return res;
    })),
  );
});
`;
}
